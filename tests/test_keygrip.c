TEST(test_valid_key_is_computable)
{
	ASSERT_EQ(keygrip_computable(VALID_PUBKEY, sizeof VALID_PUBKEY), 0);
}

TEST(test_malformed_key_rejected_not_aborted)
{
	/* Without the fork guard this input abort()s the process. */
	ASSERT_EQ(keygrip_computable(MALFORMED_PUBKEY, sizeof MALFORMED_PUBKEY),
		  -1);
}

TEST(test_valid_key_grip_still_works)
{
	char *hex = hex_encode(VALID_PUBKEY, sizeof VALID_PUBKEY);
	ASSERT_NOT_NULL(hex);
	char grip[41];
	ASSERT_EQ(compute_keygrip(hex, grip, sizeof grip), 0);
	free(hex);
}

